/**
 * Calculates length-adaptive Damerau-Levenshtein distance with transposition support.
 */
export function damerauLevenshteinDistance(source: string, target: string): number {
  const s = source.toLowerCase();
  const t = target.toLowerCase();
  const slen = s.length;
  const tlen = t.length;
  if (slen === 0) return tlen;
  if (tlen === 0) return slen;

  const d: number[][] = Array.from({ length: slen + 1 }, () => new Array(tlen + 1).fill(0));

  for (let i = 0; i <= slen; i++) d[i][0] = i;
  for (let j = 0; j <= tlen; j++) d[0][j] = j;

  for (let i = 1; i <= slen; i++) {
    for (let j = 1; j <= tlen; j++) {
      const cost = s[i - 1] === t[j - 1] ? 0 : 1;
      d[i][j] = Math.min(
        d[i - 1][j] + 1, // deletion
        d[i][j - 1] + 1, // insertion
        d[i - 1][j - 1] + cost // substitution
      );

      // Transposition
      if (i > 1 && j > 1 && s[i - 1] === t[j - 2] && s[i - 2] === t[j - 1]) {
        d[i][j] = Math.min(d[i][j], d[i - 2][j - 2] + 1);
      }
    }
  }
  return d[slen][tlen];
}

/**
 * Fast in-memory medical terminology search with exact, prefix, substring, and fuzzy matching.
 */
export function searchMedicalLexicon(
  input: string | LexiconSearchOptions
): AutocompleteSuggestion[] {
  if (!input) return [];

  const options: LexiconSearchOptions =
    typeof input === 'string' ? { query: input } : input;

  const rawQuery = (options?.query || '').trim();
  if (!rawQuery) return [];

  const cleanQuery = rawQuery.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!cleanQuery) return [];

  const maxResults = options.maxResults ?? 6;
  const enableFuzzy = options.enableFuzzy ?? true;
  const queryLen = cleanQuery.length;
  const maxFuzzyDist = queryLen <= 2 ? 0 : queryLen <= 5 ? 1 : 2;

  const results: AutocompleteSuggestion[] = [];
  const seenTerms = new Set<string>();

  for (const entry of MASTER_MEDICAL_LEXICON) {
    if (options.categoryFilter) {
      const filters = Array.isArray(options.categoryFilter)
        ? options.categoryFilter
        : [options.categoryFilter];
      if (!filters.includes(entry.category)) continue;
    }

    if (seenTerms.has(entry.term)) continue;

    const normTerm = entry.normalized;
    const termLower = entry.term.toLowerCase();

    // Contextual boost logic
    let contextBonus = 0;
    if (options.contextPreviousWord) {
      const prevNorm = options.contextPreviousWord.toLowerCase().replace(/[^a-z0-9]/g, '');
      const prevIsMed = RXNORM_MEDICATIONS.some((m) => m.normalized === prevNorm);
      const prevIsDose = CLINICAL_DOSAGES.some((d) => d.normalized === prevNorm);

      if (prevIsMed && entry.category === 'dosage') {
        contextBonus = 80;
      } else if ((prevIsMed || prevIsDose) && (entry.category === 'sig_route' || entry.category === 'dosage_form')) {
        contextBonus = 70;
      } else if (entry.category === 'sig_frequency' || entry.category === 'sig_timing') {
        contextBonus = 60;
      }
    }

    // 1. Exact Match
    if (termLower === rawQuery.toLowerCase() || normTerm === cleanQuery) {
      results.push({
        entry,
        matchType: 'exact',
        score: 1000 + entry.frequencyScore + contextBonus,
        highlightIndices: [0, entry.term.length],
      });
      seenTerms.add(entry.term);
      continue;
    }

    // Also check brand names exact match
    if (entry.brandNames && entry.brandNames.some((b) => b.toLowerCase() === rawQuery.toLowerCase())) {
      results.push({
        entry,
        matchType: 'exact',
        score: 950 + entry.frequencyScore + contextBonus,
        highlightIndices: [0, entry.term.length],
      });
      seenTerms.add(entry.term);
      continue;
    }

    // 2. Prefix Match
    if (termLower.startsWith(rawQuery.toLowerCase()) || normTerm.startsWith(cleanQuery)) {
      const matchLen = rawQuery.length;
      results.push({
        entry,
        matchType: 'prefix',
        score: 500 + (matchLen / entry.term.length) * 100 + entry.frequencyScore * 0.5 + contextBonus,
        highlightIndices: [0, matchLen],
      });
      seenTerms.add(entry.term);
      continue;
    }

    // Check brand name prefix
    if (entry.brandNames && entry.brandNames.some((b) => b.toLowerCase().startsWith(rawQuery.toLowerCase()))) {
      results.push({
        entry,
        matchType: 'prefix',
        score: 450 + entry.frequencyScore * 0.5 + contextBonus,
        highlightIndices: [0, rawQuery.length],
      });
      seenTerms.add(entry.term);
      continue;
    }

    // 3. Substring Match (only for queries >= 3 characters to avoid noisy 2-char collisions)
    if (queryLen >= 3) {
      const subIdx = termLower.indexOf(rawQuery.toLowerCase());
      if (subIdx >= 0) {
        results.push({
          entry,
          matchType: 'substring',
          score: 300 + entry.frequencyScore * 0.4 + contextBonus,
          highlightIndices: [subIdx, subIdx + rawQuery.length],
        });
        seenTerms.add(entry.term);
        continue;
      }
    }

    // 4. Fuzzy Match (Damerau-Levenshtein)
    if (enableFuzzy && queryLen >= 3) {
      const dist = damerauLevenshteinDistance(cleanQuery, normTerm);
      if (dist <= maxFuzzyDist) {
        const similarity = 1.0 - dist / Math.max(queryLen, normTerm.length);
        results.push({
          entry,
          matchType: 'fuzzy',
          score: 200 * similarity + entry.frequencyScore * 0.3 + contextBonus,
          highlightIndices: [0, entry.term.length],
        });
        seenTerms.add(entry.term);
      }
    }
  }

  // Sort descending by score
  results.sort((a, b) => b.score - a.score);
  return results.slice(0, maxResults);
}

/**
 * Returns Look-Alike Sound-Alike warning details for a specific drug term.
 */
export function getLasaWarning(
  term: string
): { isLasa: boolean; confusionWith?: string; warning?: string } | null {
  const clean = term.toLowerCase().replace(/[^a-z0-9]/g, '');
  const found = RXNORM_MEDICATIONS.find(
    (m) =>
      m.normalized === clean ||
      m.term.toLowerCase() === term.toLowerCase() ||
      (m.brandNames && m.brandNames.some((b) => b.toLowerCase() === term.toLowerCase()))
  );

  if (found && found.isLasa) {
    return {
      isLasa: true,
      confusionWith: found.lasaConfusionWith,
      warning: found.lasaWarning,
    };
  }
  return null;
}

/**
 * Returns full English expansion for Latin prescription sig code.
 */
export function getSigExpansion(code: string): string | null {
  const clean = code.toUpperCase().trim();
  const found = LATIN_SIG_CODES.find((s) => s.term.toUpperCase() === clean);
  return found ? found.description : null;
}
