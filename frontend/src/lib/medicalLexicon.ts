/**
 * frontend/src/lib/medicalLexicon.ts
 * In-memory Clinical Medical Lexicon, RxNorm Medications, Clinical Dosages & Latin Sig Codes.
 * Provides sub-millisecond prefix, substring, and length-adaptive Damerau-Levenshtein fuzzy matching.
 */

export type MedicalCategory =
  | 'medication'
  | 'dosage'
  | 'sig_frequency'
  | 'sig_route'
  | 'sig_timing'
  | 'dosage_form'
  | 'instruction';

export interface MedicalLexiconEntry {
  term: string;
  category: MedicalCategory;
  normalized: string;
  frequencyScore: number; // 0.0 to 100.0
  description: string;
  brandNames?: string[];
  standardStrengths?: string[];
  therapeuticClass?: string;
  isLasa?: boolean;
  lasaConfusionWith?: string;
  lasaWarning?: string;
}

export interface AutocompleteSuggestion {
  entry: MedicalLexiconEntry;
  matchType: 'exact' | 'prefix' | 'substring' | 'fuzzy';
  score: number;
  highlightIndices: [number, number]; // [start, end]
}

// Alias for AutocompleteSuggestion
export type LexiconMatch = AutocompleteSuggestion;

export interface LexiconSearchOptions {
  query: string;
  categoryFilter?: MedicalCategory | MedicalCategory[];
  maxResults?: number;
  contextPreviousWord?: string;
  enableFuzzy?: boolean;
}

